/**
 * 化学の「プリント流（対策プリントの方法）」解法エンジン
 * -----------------------------------------------------------------------
 * 学びの扉の化学基礎・有機・高分子対策プリントで使われている指導法：
 *   ・中和・逆滴定：「酸チームが出す H⁺ mol ＝ 塩基チームが出す OH⁻ mol」
 *   ・二段階滴定（ワルダー法）：「第1中和点＝x+y mol、第1→第2区間＝y mol」
 *   ・弱酸・強酸の希釈：「強酸 ΔpH＝log₁₀k、弱酸 ΔpH＝0.5log₁₀k（pH＝7は超えない）」
 *   ・元素分析＆分子式決定：「黄金4ステップ（質量→原子数比→分子量→分子式）」
 *   ・不飽和度 U：「U ＝ (2C ＋ 2 ＋ N − H − X)/2（酸素 O の数は無関係）」
 *   ・芳香族系統分離：「酸の強さ順（塩酸 ＞ スルホン酸 ＞ カルボン酸 ＞ 炭酸 ＞ フェノール）」
 *   ・エステル化平衡定数：「液相有機反応は溶媒が水でないため［H₂O］も必ず分子に含める」
 *   ・PVA アセタール化（ビニロン）：「アセタール環1個につき質量 ＋12 増加（反応 −OH 1mol あたり ＋6.0 g）」
 *   ・イオン交換樹脂：「捕獲した陽イオンの（価数×mol）と同じ電荷分の H⁺ を放出」
 *   ・共重合ゴム（SBR/NBR）：「N または C 質量から片方の単量体 mol 確定 → 残り質量からもう一方 mol → ジエン1単位＝Br₂ 1mol」
 *   ・電気分解・電池：「流れる電子 e⁻ の物質量 n(e⁻) ＝ It / F を全極共通の基準にする」
 *   ・溶解度・再結晶：「析出前後の飽和溶液は（溶質/水）または（溶質/溶液）の比が一定」
 *
 * 問題ごとに明示指定された `printRule` があればそれを優先し、
 * 未指定の既存問題に対してもスキル名・問題文から的確な「プリントの鉄則」を導出する。
 */

export function derivePrintRule(input: {
  printRule?: string;
  skill: string;
  stem?: string;
  explanation?: string;
}): string {
  if (input.printRule && input.printRule.trim()) {
    return input.printRule.trim();
  }
  const src = `${input.skill} ${input.stem ?? ''} ${input.explanation ?? ''}`;

  if (/(二段階滴定|ワルダー|Na2CO3|Na₂CO₃.*フェノールフタレイン.*メチルオレンジ)/.test(src)) {
    return '【二段階滴定の鉄則】第1中和点(PP変色)＝x＋y mol ／ 第1→第2区間(MO変色)＝y mol で即連立！';
  }
  if (/(逆滴定|アンモニアを吸収|残った.*中和|制酸)/.test(src)) {
    return '【逆滴定のチーム分け】酸チーム合計 H⁺ mol ＝ 塩基チーム合計（試料塩基 ＋ 滴定塩基）OH⁻ mol';
  }
  if (/(中和滴定|中和点|ホールピペット|ビュレット|メスフラスコ|コニカルビーカー)/.test(src)) {
    if (/(ぬれたまま|共洗い|水で洗|誤差|過大|過小)/.test(src)) {
      return '【滴定器具の鉄則】濃度が変わると困る器具（ホールピペット・ビュレット）＝共洗い ／ 量だけ測る・薄める器具（コニカルビーカー・メスフラスコ）＝純水洗浄のまま！';
    }
    return '【中和計算の鉄則】（酸の価数 a）× cV ＝（塩基の価数 b）× c′V′（電離度 α は中和量に無関係！）';
  }
  if (/(希釈.*pH|pH.*希釈|うすめた.*pH|0\.5\s*log)/.test(src)) {
    return '【希釈 pH の鉄則】k 倍希釈で強酸は pH ＋log₁₀k、弱酸は電離度 α が √k 倍になるため pH ＋0.5log₁₀k（7 を超えない）';
  }
  if (/(緩衝液|ヘンダーソン|CH3COOH.*CH3COONa|酢酸.*酢酸ナトリウム)/.test(src)) {
    return '【緩衝液の鉄則】[H⁺] ＝ Ka × (n酸 / n塩)（同じ容器内なので体積 V が約分され mol 比だけで決まる！）';
  }
  if (/(塩の加水分解|水溶液の液性|酸性塩|塩基性塩|正塩)/.test(src)) {
    return '【塩の液性の鉄則】親の「強い側」の液性が勝つ！（例外：NaHSO₄・NaH₂PO₄ は酸性、NaHCO₃・Na₂HPO₄ は弱塩基性）';
  }
  if (/(ビニロン|アセタール化|ブチラール)/.test(src)) {
    return '【PVA アセタール化の鉄則】−OH 2単位(88) ＋ RCHO − H₂O(18) → 環1個あたり質量差 ΔM（HCHOなら＋12、反応−OH 1molあたり＋6.0g）';
  }
  if (/(イオン交換樹脂|陽イオン交換|陰イオン交換)/.test(src)) {
    return '【イオン交換の鉄則】樹脂が捕獲したイオンの「価数 × mol（総電荷）」と等しい mol の H⁺（または OH⁻）が流出！';
  }
  if (/(SBR|NBR|共重合|アクリロニトリル|ブタジエン.*臭素)/.test(src)) {
    return '【共重合ゴム計算の鉄則】特定元素（N 等）から片方の単量体 mol を確定 → 残り質量からジエン単位 mol → ジエン1単位につき C＝C が1個残存（Br₂ 1mol 付加）';
  }
  if (/(ポリイミド|アミック酸|ピロメリット|開環重合|ナイロン|PET|ポリエチレンテレフタラート|縮合重合|平均重合度)/.test(src)) {
    return '【重合度計算の鉄則】繰り返し1単位の式量 M₀ ＝（単量体合計）− 18×（1単位中の脱離 H₂O 数）を先に確定し n ＝ M / M₀';
  }
  if (/(ペプチド|アミノ酸配列|グルタチオン|ビウレット|キサントプロテイン|ニンヒドリン|等電点|電気泳動)/.test(src)) {
    return '【アミノ酸・ペプチドの鉄則】pH ＜ pI なら陽イオン（陰極へ）、pH ＞ pI なら陰イオン（陽極へ）移動 ／ 配列は末端決定＋断片の重なりパズルで一意確定';
  }
  if (/(デンプン|セルロース|マルトース|スクロース|グルコース|還元性|グリコシド|ヘミアセタール)/.test(src)) {
    return '【糖類の鉄則】(C₆H₁₀O₅)ₙ（1単位162）＋ nH₂O(18n) → nC₆H₁₂O₆（180n）で質量は 180/162 ＝ 10/9 倍！（スクロース・トレハロースのみ二糖で還元性×）';
  }
  if (/(元素分析|塩化カルシウム管|ソーダ石灰管|組成式)/.test(src)) {
    return '【元素分析・黄金4手順】① mC＝CO₂×(12/44)、mH＝H₂O×(2/18)、mO＝試料−(mC＋mH) → ②原子数比 → ③分子量 M → ④分子式・不飽和度 U';
  }
  if (/(不飽和度|構造異性体|立体異性体|シス|トランス|不斉炭素|鏡像異性体|メソ体)/.test(src)) {
    return '【異性体・不飽和度の鉄則】U ＝ (2C＋2＋N−H−X)/2（Oは無関係）で骨格を固定し、「構造異性体のみ」か「立体異性体を含む」かを厳密区別！';
  }
  if (/(エステル化.*平衡|平衡定数.*エステル)/.test(src)) {
    return '【エステル化平衡の鉄則】有機液相反応は水が溶媒ではないため K ＝ ([エステル][H₂O]) / ([酸][醇]) と [H₂O] を必ず分子に入れる！';
  }
  if (/(けん化価|ヨウ素価|油脂|硬化油)/.test(src)) {
    return '【油脂計算の鉄則】油脂 1mol はエステル3個 → KOH(56) 3mol で完全けん化 ／ 二重結合 k 個なら I₂(254) または H₂(2.0) が k mol 付加';
  }
  if (/(分液ろうと|系統分離.*芳香族|フェノール.*安息香酸|アニリン.*抽出)/.test(src)) {
    return '【芳香族分離の鉄則】酸の強さ「塩酸 ＞ カルボン酸 ＞ 炭酸(CO₂) ＞ フェノール」より、NaHCO₃ aq ではカルボン酸のみ水層へ移る！';
  }
  if (/(銀鏡|フェーリング|ヨードホルム|フェノールエステル|サリチル酸)/.test(src)) {
    return '【有機検出＆裏切り者の鉄則】NaHCO₃発泡＝−COOH ／ FeCl₃紫＝フェノール性−OH ／ NaOH 2mol消費エステル＝フェノールエステル R−COO−Ar！';
  }
  if (/(電気分解|ファラデー|鉛蓄電池|燃料電池|ダニエル|二次電池)/.test(src)) {
    return '【電池・電気分解の鉄則】すべての電極反応を「流れた電子 n(e⁻) ＝ It / F [mol]」1本の基準に換算して質量・気体体積を出す！';
  }
  if (/(酸化還元|過マンガン酸|チオ硫酸|ヨウ素滴定|過酸化水素|酸化数)/.test(src)) {
    return '【酸化還元計算の鉄則】（酸化剤が受け取る e⁻ mol）＝（還元剤が失う e⁻ mol）で反応式を書かずに1行立式！';
  }
  if (/(溶解度積|Ksp|硫化水素.*沈殿|錯イオン|系統分離|両性金属)/.test(src)) {
    return '【無機沈殿・Ksp の鉄則】イオン積 Q ＞ Ksp で沈殿生成 ／ あ연・アルミ・スズ・鉛（ああすんなり）＝過剰 NaOH で溶け、銀・銅・亜鉛＝過剰 NH₃ で錯イオン溶解！';
  }
  if (/(蒸気圧|沸点上昇|凝固点降下|浸透圧|逆浸透|ヘンリー)/.test(src)) {
    return '【希薄溶液・気液の鉄則】電解質は電離後の全粒子倍率 i（NaClなら2、CaCl₂なら3）を必ず掛ける（ΔT＝iKm、π＝icRT）！';
  }
  if (/(反応速度|半減期|活性化エネルギー|アレニウス|ルシャトリエ|圧平衡|濃度平衡)/.test(src)) {
    return '【速度・平衡の鉄則】触媒は正・逆の Ea を同量下げて速度↑だが平衡収率は不変 ／ 温度↑は吸熱側へ平衡移動（発熱反応の収率は下がる）！';
  }
  if (/(エンタルピー|ヘスの法則|結合エネルギー|格子エネルギー|ボルン・ハーバー)/.test(src)) {
    return '【熱化学・エンタルピーの鉄則】生成エンタルピーは ΔH ＝ ΣΔfH(生成物) − ΣΔfH(反応物) ／ 結合エネルギーは「反応物 − 生成物」と向きが逆！';
  }
  if (/(結晶格子|面心立方|体心立方|六方最密|充填率|イオン結晶|配位数)/.test(src)) {
    return '【結晶格子の鉄則】単位格子中の粒子数 Z（体心2・面心4・NaCl型各4）と「最近接粒子が接する断面（対角線）」から r と a を結ぶ！';
  }
  if (/(同位体|質量スペクトル|電子配置|イオン化エネルギー|電気陰性度|極性|水素結合)/.test(src)) {
    return '【原子構造・結合の鉄則】化学的性質＝価電子数で決まる ／ 分子の極性は「結合の極性ベクトルが空間対称で打ち消し合うか」で判定！';
  }
  if (/(溶解度|再結晶|質量パーセント|モル濃度|検量線|吸光度|クロマト|Rf)/.test(src)) {
    return '【溶液・分離定量の鉄則】温度 T の飽和溶液は「溶質 : 水 : 溶液 ＝ S : 100 : (100＋S)」の比を固定して析出量を比例立式！';
  }
  return `【プリントの鉄則】「${input.skill}」の定義式・保存則を先に1行で書き出し、単位・係数のひっかけを消去する！`;
}
